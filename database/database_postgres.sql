CREATE DATABASE fiction_archive;

-- ==========================================
-- TABLE: users
-- ==========================================
CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    name VARCHAR(255),
    avatar VARCHAR(255),
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- TABLE: permissions
-- ==========================================
CREATE TABLE permissions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- TABLE: genres
-- ==========================================
CREATE TABLE genres (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- TABLE: categories
-- ==========================================
CREATE TABLE categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- TABLE: ratings
-- ==========================================
CREATE TABLE ratings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- TABLE: stories
-- ==========================================
CREATE TABLE stories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rating_id INTEGER NOT NULL,
    directory VARCHAR(255),
    title VARCHAR(255),
    cover VARCHAR(255),
    synopsis TEXT,
    is_completed BOOLEAN DEFAULT FALSE,
    is_interactive BOOLEAN DEFAULT FALSE,
    is_visible BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_stories_rating
        FOREIGN KEY (rating_id)
        REFERENCES ratings(id)
);

-- ==========================================
-- TABLE: chapters
-- ==========================================
CREATE TABLE chapters (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_id INTEGER NOT NULL,
    title VARCHAR(255),
    content TEXT,
    initial_notes TEXT,
    final_notes TEXT,
    is_visible BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chapters_story
        FOREIGN KEY (story_id)
        REFERENCES stories(id)
);

-- ==========================================
-- TABLE: user_permissions
-- ==========================================
CREATE TABLE user_permissions (
    user_id INTEGER NOT NULL,
    permission_id INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, permission_id),
    CONSTRAINT fk_user_permissions_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),
    CONSTRAINT fk_user_permissions_permission
        FOREIGN KEY (permission_id)
        REFERENCES permissions(id)
);

-- ==========================================
-- TABLE: user_stories
-- ==========================================
CREATE TABLE user_stories (
    user_id INTEGER NOT NULL,
    story_id INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, story_id),
    CONSTRAINT fk_user_stories_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),
    CONSTRAINT fk_user_stories_story
        FOREIGN KEY (story_id)
        REFERENCES stories(id)
);

-- ==========================================
-- TABLE: story_genres
-- ==========================================
CREATE TABLE story_genres (
    story_id INTEGER NOT NULL,
    genre_id INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (story_id, genre_id),
    CONSTRAINT fk_story_genres_story
        FOREIGN KEY (story_id)
        REFERENCES stories(id),
    CONSTRAINT fk_story_genres_genre
        FOREIGN KEY (genre_id)
        REFERENCES genres(id)
);

-- ==========================================
-- TABLE: story_categories
-- ==========================================
CREATE TABLE story_categories (
    story_id INTEGER NOT NULL,
    category_id INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (story_id, category_id),
    CONSTRAINT fk_story_categories_story
        FOREIGN KEY (story_id)
        REFERENCES stories(id),
    CONSTRAINT fk_story_categories_category
        FOREIGN KEY (category_id)
        REFERENCES categories(id)
);
